response = requests.get(URL, timeout=60)
response.raise_for_status()

csv_path = OUT / "official_data_en.csv"
csv_path.write_bytes(response.content)

df = pd.read_csv(csv_path)

print("Columns:", df.columns.tolist())
print("Rows:", len(df))
